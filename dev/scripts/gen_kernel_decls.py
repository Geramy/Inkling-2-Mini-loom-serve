#!/usr/bin/env python3
"""Writes package/dispatch/kernel_decls.loom: one kernel.decl per kernel.def under package/kernel/ (workload parameters and launch signature)."""
import glob
import os
import re

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "package")
pat = re.compile(r'^kernel\.def\s+(?:public\s+)?(?:export\("[^"]*"\)\s+)?(@[\w.]+)\(([^)]*)\)\s*\{.*?^\}\s*launch\(([^)]*)\)\s*\{', re.S | re.M)
out = ["// Declarations of every kernel launched by the dispatch commands. Generated by scripts/gen_kernel_decls.py from package/kernel/*/*.loom.\n"]
for path in sorted(glob.glob(os.path.join(root, "kernel", "*", "*.loom"))):
    for m in pat.finditer(open(path).read()):
        launch = " ".join(m.group(3).split())
        out.append("kernel.decl %s(%s) launch(%s)\n" % (m.group(1), m.group(2), launch))
open(os.path.join(root, "dispatch", "kernel_decls.loom"), "w").write("\n".join(out))
print(len(out) - 1, "kernels")
